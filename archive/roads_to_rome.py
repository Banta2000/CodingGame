def getNeighbours(graph, node):
    lst1 = [x[0] for x in graph if x[1] == node]
    lst2 = [x[1] for x in graph if x[0] == node]
    return set(lst1 + lst2)


def dfs(graph, node, visited):
    visited.add(node)

    if node == 100:
        print("Found", visited)
        return 1

    neighbours = getNeighbours(graph, node) - visited
    result = 0
    for n in neighbours:
        result += dfs(graph, n, visited)
        visited.remove(n)

    return result


