def _get_neighbors(point: Point):
    r, c = point
    return [(r - 1, c), (r + 1, c), (r, c - 1), (r, c + 1)]


def mark_island(start: Point, num: int):
    stack = [start]
    while stack:
        curr = stack.pop(0)
        if board[curr] != "#":
            continue
        board[curr] = num
        for n in _get_neighbors(curr):
            if n in board:
                stack.append(n)


def mark_islands():
    num_rows = max(k[0] for k in board.keys()) + 1
    num_cols = max(k[1] for k in board.keys()) + 1
    i = 1
    for r in range(num_rows):
        for c in range(num_cols):
            p = r, c
            if board[p] == "#":
                mark_island(p, i)
                i += 1


